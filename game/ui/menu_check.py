from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(args=["--use-gl=angle", "--enable-unsafe-swiftshader"]); pg = b.new_page(viewport={"width": 1280, "height": 800})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("http://localhost:5173"); pg.wait_for_function("window.HEEL_UI && HEEL_UI.state === 'title'", timeout=30000)
    pg.keyboard.press("Enter"); pg.wait_for_function("HEEL_UI.state === 'menu'")
    pg.wait_for_timeout(600)
    print("menu:", [t.strip() for t in pg.locator("#s-menu .mlist > *").all_inner_texts()][:8])
    pg.keyboard.press("ArrowDown"); pg.wait_for_timeout(200); pg.keyboard.press("ArrowDown"); pg.wait_for_timeout(200)
    pg.keyboard.press("ArrowDown"); pg.wait_for_timeout(200); pg.keyboard.press("Enter"); pg.wait_for_timeout(400)
    print("locked toast:", pg.evaluate("[...document.querySelectorAll('.toast, #toast')].map(e => e.textContent).join(' | ')"))
    pg.screenshot(path="../docs/shots/menu-ladder.png")
    pg.keyboard.press("ArrowUp"); pg.wait_for_timeout(200); pg.keyboard.press("ArrowUp"); pg.wait_for_timeout(200); pg.keyboard.press("Enter"); pg.wait_for_timeout(600)
    print("after ladder enter:", pg.evaluate("HEEL_UI.state"))
    pg.keyboard.press("Enter"); pg.wait_for_timeout(3000)
    print("url:", pg.url)
    pg.wait_for_timeout(4000); pg.keyboard.press("Escape"); pg.wait_for_timeout(500)
    print("ladder pause open:", pg.evaluate("document.getElementById('lp')?.classList.contains('on')"), pg.inner_text("#lp nav") .replace("\n", " | "))
    pg.screenshot(path="../docs/shots/ladder-pause.png")
    pg.evaluate("document.querySelector('#lp [data-a=menu]').click()"); pg.wait_for_timeout(2500); print("back to:", pg.url)
    pg.wait_for_function("window.HEEL_UI && HEEL_UI.state === 'title'", timeout=30000)
    pg.keyboard.press("Enter"); pg.wait_for_function("HEEL_UI.state === 'menu'"); pg.wait_for_timeout(500); pg.keyboard.press("Enter")
    pg.wait_for_function("HEEL_UI.state === 'select'"); pg.wait_for_timeout(400); pg.keyboard.press("Enter")
    pg.wait_for_function("HEEL_UI.state === 'match'", timeout=10000); pg.wait_for_timeout(4500)
    pg.keyboard.press("Escape"); pg.wait_for_timeout(500)
    print("pause items:", pg.locator("#s-pause .mlist > *").all_inner_texts())
    pg.screenshot(path="../docs/shots/pause-restart.png")
    t0 = pg.evaluate("G.state.clock"); pg.keyboard.press("ArrowDown"); pg.wait_for_timeout(200); pg.keyboard.press("Enter"); pg.wait_for_timeout(1500)
    print("restart:", pg.evaluate("HEEL_UI.state"), "clock before", round(t0, 1), "after", round(pg.evaluate("G.state.clock"), 1), "intro", round(pg.evaluate("G.state.introT"), 1))
    print("ERRORS:", errs or "none"); b.close()
