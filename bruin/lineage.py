"""Write docs/lanes/bruin-lineage.txt: asset lineage (bruin lineage --full) and column lineage
(bruin internal parse-pipeline -c). python3 bruin/lineage.py"""
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "docs" / "lanes" / "bruin-lineage.txt"
ASSETS = ["assets/raw/events.py", "assets/staging/stg_events.sql", "assets/marts/habits.sql",
          "assets/marts/relationships.sql", "assets/marts/taunt_tone.asset.yml"]


def bruin(*args):
    return subprocess.run(["bruin", *args], cwd=HERE, capture_output=True, text=True, check=True).stdout


parts = ["# HEEL TURN Bruin lineage, generated by `python3 bruin/lineage.py`\n"]
for a in ASSETS:
    parts.append(f"$ bruin lineage --full {a}\n{bruin('lineage', '--full', a)}")

pipe = json.loads(bruin("internal", "parse-pipeline", "-c", "."))
parts.append("$ bruin internal parse-pipeline -c .   (column lineage, column <- upstream table.column)\n")
for asset in sorted(pipe["assets"], key=lambda x: x["name"]):
    deps = ", ".join(u["value"] for u in asset.get("upstreams") or [])
    parts.append(f"{asset['name']}  <- [{deps}]")
    for col in asset.get("columns") or []:
        ups = ", ".join(f"{u['table']}.{u['column']}" for u in col.get("upstreams") or [])
        parts.append(f"    {col['name']:<14} <- {ups or '(computed / source)'}")
OUT.write_text("\n".join(parts) + "\n")
print(f"wrote {OUT}")
